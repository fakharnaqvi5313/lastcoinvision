package feemarket

import (
	autocliv1 "cosmossdk.io/api/cosmos/autocli/v1"
	"github.com/spf13/cobra"

	modulev1 "github.com/lastcoinvision/lcv/api/lcv/feemarket"
	"github.com/lastcoinvision/lcv/x/feemarket/client/cli"
)

// GetQueryCmd implements the autocli.HasCustomQueryCommand interface. It
// takes over the "params" query specifically so its output goes through
// codec.ProtoCodec.MarshalJSON (via clientCtx.PrintProto) instead of
// AutoCLI's default aminojson response encoder, which doesn't know how to
// render the gogoproto customtype LegacyDec fields in Params — see
// x/feemarket/client/cli/query.go and modules/feemarket/SPEC.md.
func (am AppModule) GetQueryCmd() *cobra.Command {
	return cli.GetQueryCmd()
}

// AutoCLIOptions implements the autocli.HasAutoCLIConfig interface. Query's
// EnhanceCustomCommand is set so AutoCLI still layers in any RPCs not
// already present in GetQueryCmd's hand-written tree (there are none today,
// but this keeps future additions automatic); "params" itself is served by
// the custom command above, not regenerated by AutoCLI.
func (am AppModule) AutoCLIOptions() *autocliv1.ModuleOptions {
	return &autocliv1.ModuleOptions{
		Query: &autocliv1.ServiceCommandDescriptor{
			Service:              modulev1.Query_ServiceDesc.ServiceName,
			EnhanceCustomCommand: true,
			RpcCommandOptions: []*autocliv1.RpcCommandOptions{
				{
					RpcMethod: "Params",
					Use:       "params",
					Short:     "Shows the parameters of the module",
				},
				// this line is used by ignite scaffolding # autocli/query
			},
		},
		Tx: &autocliv1.ServiceCommandDescriptor{
			Service:              modulev1.Msg_ServiceDesc.ServiceName,
			EnhanceCustomCommand: true, // only required if you want to use the custom command
			RpcCommandOptions: []*autocliv1.RpcCommandOptions{
				{
					RpcMethod: "UpdateParams",
					Skip:      true, // skipped because authority gated
				},
				// this line is used by ignite scaffolding # autocli/tx
			},
		},
	}
}
